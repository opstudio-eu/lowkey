#!/usr/bin/env python3
"""Builds the emoji search keywords from the Unicode CLDR annotations (Unicode License V3).

For every language in LANGUAGES it downloads CLDR's `annotations/<lang>.xml` and
`annotationsDerived/<lang>.xml` at the pinned release, checks their SHA-256, and writes
`app/src/main/assets/emoji/keywords-<lang>.txt` with one emoji per line:

    emoji<TAB>name<TAB>keyword|keyword|...

Only emoji in `emoji/emoji-test.txt` are kept, under that file's fully-qualified form, and only
those without a skin tone (the panel offers tones on the base emoji). The name is CLDR's short
name ("tts"); the keywords are CLDR's search words for that emoji, without the name itself.

Usage: scripts/build-emoji-keywords.py    (run from the repo root; needs network)
"""
import hashlib
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

RELEASE = "release-48"
SOURCE = f"https://raw.githubusercontent.com/unicode-org/cldr/{RELEASE}/common"
LANGUAGES = {
    "en": {
        "annotations": "8511aadd046fdba2f0ffe590266ced8bbf48175ad139b2675d85d7141057b235",
        "annotationsDerived": "d76bd041c8c9e7b00b716aff8b7d9dbf509877010e191d5efd068be2553e066e",
    },
    "nl": {
        "annotations": "b8bbd9ae8a642a100cd368a71535b23588beb91a342786a3cf00aaea8cd16f02",
        "annotationsDerived": "8f9254de9a8ffdf9a977d626893053e35d21ea099a6acabc38423d10ba8bd02f",
    },
}
EMOJI = Path("app/src/main/assets/emoji")
TONES = set(range(0x1F3FB, 0x1F400))


def key(value: str) -> str:
    """The emoji without variation selectors, as CLDR writes most of them."""
    return value.replace("️", "")


def catalog() -> dict[str, str]:
    """Fully-qualified emoji from emoji-test.txt by [key], in file order."""
    out: dict[str, str] = {}
    for line in (EMOJI / "emoji-test.txt").read_text(encoding="utf-8").splitlines():
        if ";" not in line or line.startswith("#"):
            continue
        if line.split(";", 1)[1].split("#", 1)[0].strip() != "fully-qualified":
            continue
        value = "".join(chr(int(cp, 16)) for cp in line.split(";", 1)[0].split())
        if not any(ord(c) in TONES for c in value):
            out.setdefault(key(value), value)
    return out


def fetch(kind: str, lang: str, sha256: str) -> bytes:
    data = urllib.request.urlopen(f"{SOURCE}/{kind}/{lang}.xml", timeout=60).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != sha256:
        sys.exit(f"{kind}/{lang}.xml: SHA-256 {digest}, expected {sha256}")
    return data


def annotations(data: bytes, names: dict, words: dict) -> None:
    for node in ET.fromstring(data).iter("annotation"):
        text = (node.text or "").strip()
        if not text or text == "↑↑↑":
            continue
        cp = node.get("cp", "")
        if node.get("type") == "tts":
            names.setdefault(cp, text)
        else:
            words.setdefault(cp, [w.strip() for w in text.split("|") if w.strip()])


def build(lang: str, pins: dict, emoji: dict[str, str]) -> str:
    names: dict[str, str] = {}
    words: dict[str, list[str]] = {}
    for kind in ("annotations", "annotationsDerived"):
        annotations(fetch(kind, lang, pins[kind]), names, words)
    lines = [
        f"# Emoji names and search keywords ({lang}) from Unicode CLDR {RELEASE.split('-')[1]},",
        f"# {SOURCE}/annotations/{lang}.xml and annotationsDerived/{lang}.xml.",
        "# Copyright Unicode, Inc. Unicode License V3, see licenses/UNICODE-LICENSE.txt.",
        "# Generated by scripts/build-emoji-keywords.py. emoji<TAB>name<TAB>keyword|keyword",
    ]
    for k, value in emoji.items():
        name = names.get(k) or names.get(value)
        if name is None:
            continue
        keywords = [w for w in words.get(k) or words.get(value) or [] if w.lower() != name.lower()]
        clean = [s.replace("\t", " ").replace("|", "/") for s in [name] + keywords]
        lines.append(f"{value}\t{clean[0]}\t{'|'.join(clean[1:])}")
    return "\n".join(lines) + "\n"


def main() -> None:
    emoji = catalog()
    for lang, pins in LANGUAGES.items():
        out = EMOJI / f"keywords-{lang}.txt"
        out.write_text(build(lang, pins, emoji), encoding="utf-8")
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
